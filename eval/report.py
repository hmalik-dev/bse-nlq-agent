"""Render one evaluation run as the markdown the README quotes."""

from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from eval.run import Decision, ModelRun, Record

PASS_MARK = "✅"
FAIL_MARK = "❌"


FAKE_BANNER = (
    "> **Not a measured run.** These numbers come from `eval.run --fake`, a scripted "
    "client that answers from the reference SQL. No model was called."
)


def write_report(
    path: Path,
    runs: list[ModelRun],
    decision: Decision,
    today: date,
    database: Path,
    *,
    fake: bool = False,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_report(runs, decision, today, database, fake=fake), encoding="utf-8")


def render_report(
    runs: list[ModelRun], decision: Decision, today: date, database: Path, *, fake: bool = False
) -> str:
    questions = len(runs[0].records)
    sections = [
        "# Accuracy evaluation",
        "",
        *([FAKE_BANNER, ""] if fake else []),
        f"Generated by `uv run python -m eval.run{' --fake' if fake else ''}` "
        f"on {date.today().isoformat()}. "
        f"Each model was asked the {questions} golden questions once, in order, with "
        f"today pinned to {today.isoformat()} against `data/{database.name}`.",
        "",
        "## Summary",
        "",
        *_summary_table(runs),
        "",
        "## Decision",
        "",
        _decision_paragraph(decision),
        "",
        "## Per question",
        "",
        *_matrix_table(runs),
    ]
    return "\n".join(sections) + "\n"


def _summary_table(runs: list[ModelRun]) -> list[str]:
    lines = [
        "| Model | Passed | Accuracy | Median latency | Mean cost / question | Total cost |",
        "|---|---|---|---|---|---|",
    ]
    for run in runs:
        lines.append(
            f"| `{run.model}` | {run.passes}/{len(run.records)} | {run.accuracy:.0%} "
            f"| {run.median_latency_ms:,.0f} ms | ${run.mean_cost_usd:.4f} "
            f"| ${run.total_cost_usd:.4f} |"
        )
    return lines


def _decision_paragraph(decision: Decision) -> str:
    rule = (
        "Rule, fixed before the run: the cheapest model by mean cost per question that "
        "comes within one question of the best score and gets every unsafe and "
        "unanswerable question right."
    )
    if decision.winner is None:
        return f"{rule} **No model qualifies**: {decision.reason}."
    return f"{rule} **Winner: `{decision.winner}`** ({decision.reason})."


def _matrix_table(runs: list[ModelRun]) -> list[str]:
    models = " | ".join(f"`{run.model}`" for run in runs)
    lines = [
        f"| # | Question | Tags | Expect | {models} |",
        "|---|---|---|---|" + "---|" * len(runs),
    ]
    for index in range(len(runs[0].records)):
        first = runs[0].records[index]
        cells = " | ".join(_outcome_cell(run.records[index]) for run in runs)
        lines.append(
            f"| {index + 1} | {first.question} | {', '.join(first.tags)} "
            f"| {first.expect} | {cells} |"
        )
    return lines


def _outcome_cell(record: Record) -> str:
    mark = PASS_MARK if record.passed else FAIL_MARK
    detail = f"{record.status} ({record.error})" if record.error else record.status
    return f"{mark} {detail}"
